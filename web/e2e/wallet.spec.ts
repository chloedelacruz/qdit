import { Keypair, Networks, TransactionBuilder } from "@stellar/stellar-sdk";
import { expect, test, type Page } from "@playwright/test";

/**
 * `/wallet`: connect, balance, send — with a real Testnet account and no
 * wallet extension.
 *
 * ---------------------------------------------------------------------------
 * HOW A WALLET IS CONNECTED WITHOUT ONE INSTALLED
 * ---------------------------------------------------------------------------
 * `wallet-auth.spec.ts` sidesteps the wallet kit by calling the challenge
 * routes itself. This page cannot be tested that way: connecting, reading the
 * balance and signing all happen inside the kit, in the browser.
 *
 * So the page is given a wallet. The kit's Hana module looks for a provider at
 * `window.hanaWallet.stellar` and calls `getPublicKey()` and
 * `signTransaction()` on it — nothing else. `addInitScript` puts one there
 * before any page script runs, and its `signTransaction` hands the XDR to Node
 * through `exposeFunction`, where a keypair generated by this spec signs it.
 * Everything from the modal onwards is the app's real code: the kit picks the
 * module, the panel fetches `/api/balance`, the form calls `preparePayment`
 * and `sendPayment`, and the transaction lands on Testnet.
 *
 * The provider signs only on the Testnet passphrase. A Mainnet signature would
 * be refused by the network anyway; refusing here makes a misconfigured run
 * fail on this line instead of on a ledger error.
 *
 * ---------------------------------------------------------------------------
 * WHAT THIS COSTS
 * ---------------------------------------------------------------------------
 * The payment test funds a throwaway account with Friendbot and sends 2 XLM
 * of test lumens to a second throwaway account. Nothing is written to the
 * database, so there is nothing for the teardown to remove. It depends on
 * Friendbot and Horizon being up, which is the point of a payment test.
 */

const FRIENDBOT = "https://friendbot.stellar.org";
const HORIZON = "https://horizon-testnet.stellar.org";

async function giveWallet(page: Page, keypair: Keypair): Promise<void> {
  await page.exposeFunction(
    "__e2eSignTransaction",
    (xdr: string, passphrase: string | undefined): string => {
      if (passphrase && passphrase !== Networks.TESTNET) {
        throw new Error(`e2e wallet signs on Testnet only, not "${passphrase}".`);
      }
      const transaction = TransactionBuilder.fromXDR(xdr, Networks.TESTNET);
      transaction.sign(keypair);
      return transaction.toXDR();
    },
  );

  await page.addInitScript((address: string) => {
    // Looked up at call time, not here: the binding is installed by its own
    // init script, and the order of the two is not worth depending on.
    const sign = (xdr: string, passphrase?: string) =>
      (window as unknown as {
        __e2eSignTransaction: (xdr: string, passphrase?: string) => Promise<string>;
      }).__e2eSignTransaction(xdr, passphrase);

    (window as unknown as { hanaWallet: unknown }).hanaWallet = {
      stellar: {
        getPublicKey: async () => address,
        signTransaction: async ({
          xdr,
          networkPassphrase,
        }: {
          xdr: string;
          networkPassphrase?: string;
        }) => sign(xdr, networkPassphrase),
        signAuthEntry: async () => {
          throw new Error("e2e wallet does not sign auth entries.");
        },
        signMessage: async () => {
          throw new Error("e2e wallet does not sign messages.");
        },
      },
    };
  }, keypair.publicKey());
}

async function connect(page: Page): Promise<void> {
  await page.goto("/wallet");
  await expect(page.getByRole("heading", { level: 1, name: "Wallet" })).toBeVisible();

  await page.getByRole("button", { name: "Connect wallet" }).click();
  // The kit's chooser is plain DOM appended to <body>, one <li> per wallet.
  await page.locator("li", { hasText: "Hana Wallet" }).click();
}

async function fund(address: string): Promise<void> {
  const response = await fetch(`${FRIENDBOT}?addr=${address}`, {
    signal: AbortSignal.timeout(30_000),
  });
  expect(response.ok, `Friendbot refused ${address}: ${await response.text()}`).toBe(true);
}

// One account per test, so nothing here shares state; serial only to keep
// Friendbot from seeing a burst from one address.
test.describe.configure({ mode: "serial" });

test.describe("wallet page", () => {
  test("with no wallet connected, it offers to connect one", async ({ page }) => {
    await page.goto("/wallet");

    await expect(page.getByText("No wallet connected.")).toBeVisible();
    await expect(page.getByRole("button", { name: "Connect wallet" })).toBeEnabled();
    // No balance or send form for an address nobody has given it.
    await expect(page.getByRole("region", { name: "Send XLM" })).toHaveCount(0);
  });

  test("connecting shows the address and says an unfunded account holds nothing", async ({
    page,
  }) => {
    const keypair = Keypair.random();
    await giveWallet(page, keypair);
    await connect(page);

    const connection = page.getByRole("region", { name: "Wallet connection" });
    await expect(connection.locator(`[title="${keypair.publicKey()}"]`)).toBeVisible();
    await expect(connection.getByText("Connected on Testnet")).toBeVisible();

    // A fresh keypair has no ledger entry: the honest answer is "does not
    // exist yet", with the one-click Friendbot fix, not a zero balance.
    const balance = page.getByRole("region", { name: "Wallet balance" });
    await expect(balance.getByText(/does not exist on testnet yet/)).toBeVisible();
    await expect(balance.getByRole("button", { name: /fund/i })).toBeVisible();
  });

  test("disconnecting returns to the connect state", async ({ page }) => {
    await giveWallet(page, Keypair.random());
    await connect(page);
    await expect(page.getByRole("button", { name: "Disconnect" })).toBeVisible();

    await page.getByRole("button", { name: "Disconnect" }).click();

    await expect(page.getByText("No wallet connected.")).toBeVisible();
    await expect(page.getByRole("region", { name: "Wallet balance" })).toHaveCount(0);
  });

  test("a funded account shows its balance and sends a Testnet payment", async ({ page }) => {
    test.setTimeout(150_000);

    const source = Keypair.random();
    const destination = Keypair.random();
    await fund(source.publicKey());

    await giveWallet(page, source);
    await connect(page);

    // Friendbot gives exactly 10,000 XLM. Spendable is less than that, which
    // is the reason the panel shows three numbers.
    const balance = page.getByRole("region", { name: "Wallet balance" });
    await expect(balance.getByText("10,000.00", { exact: true })).toBeVisible({
      timeout: 30_000,
    });

    const send = page.getByRole("region", { name: "Send XLM" });
    await send.getByLabel("Destination").fill(destination.publicKey());
    await send.getByLabel("Amount (XLM)").fill("2");
    await send.getByLabel("Memo").fill("e2e wallet payment");
    await send.getByRole("button", { name: "Send XLM" }).click();

    // The destination did not exist, so the app had to build a createAccount
    // rather than a payment, and says so.
    const receipt = send.locator('[data-slot="payment-receipt"]');
    await expect(receipt).toContainText("Sent 2.00 XLM, creating the destination account.", {
      timeout: 90_000,
    });

    const txHash = await receipt.locator('[data-slot="hash"]').first().getAttribute("title");
    expect(txHash).toMatch(/^[0-9a-f]{64}$/);

    // The ledger, not the page, is the judge: the transaction exists and the
    // destination now holds exactly what was sent.
    const tx = await fetch(`${HORIZON}/transactions/${txHash}`);
    expect(tx.ok).toBe(true);
    expect(((await tx.json()) as { successful: boolean }).successful).toBe(true);

    const account = await fetch(`${HORIZON}/accounts/${destination.publicKey()}`);
    expect(account.ok).toBe(true);
    const { balances } = (await account.json()) as {
      balances: { asset_type: string; balance: string }[];
    };
    expect(balances.find((b) => b.asset_type === "native")?.balance).toBe("2.0000000");

    // And the panel refetched: the total is no longer Friendbot's round number.
    await expect(balance.getByText("10,000.00", { exact: true })).toHaveCount(0);
  });
});
